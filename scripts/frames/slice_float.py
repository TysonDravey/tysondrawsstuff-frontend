"""Cut floating ("floater") frames from a 3x2 sheet. Each frame's outer edge is snapped from a rough box; the
opening is where the pale backing starts, found by walking out from the middle until it gets darker. The
recessed lip stays part of the frame, so the canvas looks like it floats inside it.
Writes NAME.webp + frames.json (+ _contact.jpg preview) in the same format as slice_manual.py.

usage: python slice_float.py SHEET OUT_DIR
"""
import json
import sys
from pathlib import Path

import numpy as np
from PIL import Image, ImageDraw

sheet, out = Path(sys.argv[1]), Path(sys.argv[2])
out.mkdir(parents=True, exist_ok=True)
im = Image.open(sheet).convert("RGB")
g = np.array(im.convert("L"), dtype=np.float32)
gx = np.abs(np.diff(g, axis=1, prepend=g[:, :1]))
gy = np.abs(np.diff(g, axis=0, prepend=g[:1, :]))

# name, rough outer box (x0, y0, x1, y1) on the 1536x1024 sheet
F = [
    ("float-black",      (22, 27, 492, 481)),
    ("float-walnut",     (532, 27, 1002, 478)),
    ("float-grey-barn",  (1043, 27, 1514, 480)),
    ("float-red-chippy", (22, 538, 492, 990)),
    ("float-brown-gold", (532, 538, 1002, 990)),
    ("float-whitewash",  (1043, 538, 1515, 990)),
]
R = 10


def snap_x(x, y0, y1):
    lo, hi = max(1, x - R), min(g.shape[1] - 1, x + R)
    return lo + int(gx[y0 + (y1 - y0) // 4: y1 - (y1 - y0) // 4, lo:hi].mean(axis=0).argmax())


def snap_y(y, x0, x1):
    lo, hi = max(1, y - R), min(g.shape[0] - 1, y + R)
    return lo + int(gy[lo:hi, x0 + (x1 - x0) // 4: x1 - (x1 - x0) // 4].mean(axis=1).argmax())


def opening(x0, y0, x1, y1):
    """Edges of the pale backing: walk out from the centre along a band until clearly darker."""
    cx, cy = (x0 + x1) // 2, (y0 + y1) // 2
    band = 40
    base = np.median(g[cy - 40:cy + 40, cx - 40:cx + 40])
    row = np.median(g[cy - band:cy + band, x0:x1], axis=0)   # brightness across, per column
    col = np.median(g[y0:y1, cx - band:cx + band], axis=1)   # brightness down, per row
    thr = min(125, base - 70)  # the dark lip; the backing fades softly before it, and that must not show

    def walk(line, start, step):
        i = start
        while 0 < i < len(line) - 1 and line[i] > thr:
            i += step
        return i

    lx, rx = walk(row, cx - x0, -1), walk(row, cx - x0, 1)
    ty, by = walk(col, cy - y0, -1), walk(col, cy - y0, 1)
    return x0 + lx, y0 + ty, x0 + rx, y0 + by


meta = []
for i, (name, (ox0, oy0, ox1, oy1)) in enumerate(F, 1):
    ox0, ox1 = snap_x(ox0, oy0, oy1), snap_x(ox1, oy0, oy1)
    oy0, oy1 = snap_y(oy0, ox0, ox1), snap_y(oy1, ox0, ox1)
    x0, y0, x1, y1 = ox0 + 2, oy0 + 2, ox1 - 2, oy1 - 2
    ix0, iy0, ix1, iy1 = opening(x0, y0, x1, y1)
    sides = [iy0 - y0, x1 - ix1, y1 - iy1, ix0 - x0]  # top right bottom left, to the lip's edge
    sl = sides  # per side: the lips differ (perspective), and an even width would show backing
    crop = im.crop((x0, y0, x1, y1))
    crop.save(out / f"{name}.webp", quality=90, method=6)
    meta.append({"id": i, "name": name, "w": x1 - x0, "h": y1 - y0, "slice": sl, "sides": sides})
    print(i, name, crop.size, "sides", sides, "slice", sl[0])

(out / "frames.json").write_text(json.dumps(meta, indent=1))

cols, pad = 3, 12
tw = max(m["w"] for m in meta) + pad
th = max(m["h"] for m in meta) + pad + 14
prev = Image.new("RGB", (tw * cols, th * 2), (74, 20, 24))
d = ImageDraw.Draw(prev)
for k, m in enumerate(meta):
    px, py = (k % cols) * tw + 6, (k // cols) * th + 18
    prev.paste(Image.open(out / f"{m['name']}.webp"), (px, py))
    t, r, b, l = m["slice"]
    d.rectangle([px + l, py + t, px + m["w"] - r, py + m["h"] - b], outline=(0, 255, 120), width=2)
    d.text((px, py - 14), f"{m['id']} {m['name']}", fill=(255, 255, 255))
prev.save(out / "_contact.jpg", quality=85)

# Install into the site when a frontend folder is given (3rd argument): public/frames/*.webp,
# src/app/frames-float.css and src/lib/frames-float.ts.
if len(sys.argv) > 3:
    import shutil
    fe = Path(sys.argv[3])
    SCALE = 0.45  # a little slimmer than the regular frames (0.5): floaters are deep
    css = ["/* GENERATED by scripts/frames/slice_float.py: floating frames for paintings on canvas.",
           "   Per-side widths (--fw-t/r/b/l) because the frames are drawn in slight perspective. */"]
    names = []
    for m in meta:
        key = m["name"].replace("-", "_")
        names.append(key)
        shutil.copyfile(out / f"{m['name']}.webp", fe / "public" / "frames" / f"{key}.webp")
        t, r, b, l = m["slice"]
        css.append(f".frame-{key} {{ --fw: {round(min(m['slice']) * SCALE, 1)}px; "
                   f"--fw-t: {round(t * SCALE, 1)}px; --fw-r: {round(r * SCALE, 1)}px; "
                   f"--fw-b: {round(b * SCALE, 1)}px; --fw-l: {round(l * SCALE, 1)}px; }}\n"
                   f".frame-{key}::before {{ border-image: url('/frames/{key}.webp') {t} {r} {b} {l} stretch; }}")
    (fe / "src" / "app" / "frames-float.css").write_text("\n".join(css) + "\n")
    (fe / "src" / "lib" / "frames-float.ts").write_text(
        "// GENERATED by scripts/frames/slice_float.py: floating frames, used for paintings on canvas.\n"
        "// Keep in sync with the `frame` enumeration in the backend product schema.\n"
        f"export const FLOAT_NAMES = {json.dumps(names, indent=2)} as const;\n")
    print("installed:", ", ".join(names))
